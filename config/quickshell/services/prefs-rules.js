function value(v, r) {
    switch (r[1]) {
    case "bool":   return typeof v === "boolean" ? v : undefined;
    case "truthy": return v ? v : undefined;
    case "str":    return (typeof v === "string" && v !== "") ? v : undefined;
    case "string": return typeof v === "string" ? v : undefined;
    case "nonneg": return (typeof v === "number" && v >= 0) ? v : undefined;
    case "enum":   return r[2].indexOf(v) >= 0 ? v : undefined;
    case "num":    return typeof v === "number" ? Math.max(r[2], Math.min(r[3], r[4] ? Math.round(v / r[4]) * r[4] : v)) : undefined;
    }
    return undefined;
}
